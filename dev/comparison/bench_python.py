"""bench_python.py — Python MGGP benchmark harness for MATLAB vs Python comparison.

Reads data/siso_ref.csv (generated by generate_dataset.m), runs MGGP for each
seed with the agreed comparison params (see PROTOCOL.md), and saves results to
results/python_bench_<timestamp>.json.

Usage:
    python bench_python.py [--mggp-src PATH]

Options:
    --mggp-src PATH   Path to directory containing mggp.py / base.py.
                      Default: looks for MGGP_PYTHON_SRC env var, then
                      ../../../../IC/mggptestePYTHON/src relative to this file.
"""
import argparse
import json
import math
import os
import sys
import time
import tracemalloc
from datetime import datetime

import numpy as np
import pandas as pd


# ─── resolve mggp source ─────────────────────────────────────────────────────

def _find_mggp_src(cli_arg):
    if cli_arg:
        return cli_arg
    env = os.environ.get('MGGP_PYTHON_SRC')
    if env:
        return env
    # relative fallback: dev/comparison/ → MGGP_Vmatlab → IC → mggptestePYTHON/src
    here = os.path.dirname(os.path.abspath(__file__))
    candidate = os.path.normpath(
        os.path.join(here, '..', '..', '..', '..', 'IC', 'mggptestePYTHON', 'src')
    )
    return candidate


# ─── params (aligned with PROTOCOL.md) ──────────────────────────────────────

SEEDS       = [42, 43, 44]
POP_SIZE    = 100
GENERATIONS = 50
N_DELAYS    = [1, 2, 3]
N_TERMS     = 5
MAX_HEIGHT  = 2
K_WINDOW    = 5
CROSSOVER   = 0.8
TOURNSIZE   = 2
ELITE_PCT   = 10
EVAL_TYPE   = 'MShooting'
N_JOBS      = -1   # all cores; set to 1 to match CUDA package

SPLIT = 0.7   # 70% identification


# ─── helpers ─────────────────────────────────────────────────────────────────

def load_dataset(data_dir):
    csv = os.path.join(data_dir, 'siso_ref.csv')
    if not os.path.exists(csv):
        raise FileNotFoundError(
            f"Dataset not found: {csv}\n"
            "Run generate_dataset.m in MATLAB first."
        )
    df  = pd.read_csv(csv)
    y   = df['y'].values.reshape(-1, 1)
    u   = df['u1'].values.reshape(-1, 1)
    n   = len(y)
    n_id = round(n * SPLIT)
    return (y[:n_id], u[:n_id]), (y[n_id:], u[n_id:])


def osa_rmse(model, y_val, u_val):
    try:
        y_pred = model.predict(u_val, y_val, prediction_type='OSA')
        lag = model.lagMax if hasattr(model, 'lagMax') else 3
        y_t  = y_val[lag:].ravel()
        y_p  = y_pred[lag:].ravel() if len(y_pred) > lag else y_pred.ravel()
        n    = min(len(y_t), len(y_p))
        return math.sqrt(np.mean((y_t[:n] - y_p[:n]) ** 2))
    except Exception as e:
        print(f"  [WARN] OSA predict failed: {e}")
        return float('nan')


def fr_rmse(model, y_val, u_val):
    try:
        y_pred = model.predict(u_val, y_val, prediction_type='FreeRun')
        lag = model.lagMax if hasattr(model, 'lagMax') else 3
        y_t  = y_val[lag:].ravel()
        y_p  = y_pred[lag:].ravel() if len(y_pred) > lag else y_pred.ravel()
        n    = min(len(y_t), len(y_p))
        return math.sqrt(np.mean((y_t[:n] - y_p[:n]) ** 2))
    except Exception as e:
        print(f"  [WARN] FreeRun predict failed: {e}")
        return float('nan')


def convergence_gen(logbook, threshold=0.05):
    for entry in logbook:
        if entry.get('min', float('inf')) < threshold:
            return entry.get('gen', -1)
    return -1


# ─── main ────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--mggp-src', default=None)
    args = parser.parse_args()

    mggp_src = _find_mggp_src(args.mggp_src)
    if not os.path.isdir(mggp_src):
        print(f"[ERROR] mggp source not found: {mggp_src}")
        print("Set MGGP_PYTHON_SRC env var or pass --mggp-src <path>")
        sys.exit(1)

    sys.path.insert(0, mggp_src)
    from mggp import MGGP  # noqa: E402

    print(f"mggp source: {mggp_src}")
    print(f"n_jobs={N_JOBS}  seeds={SEEDS}\n")

    here     = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.join(here, 'data')
    res_dir  = os.path.join(here, 'results')
    os.makedirs(res_dir, exist_ok=True)

    (y_id, u_id), (y_val, u_val) = load_dataset(data_dir)
    print(f"Dataset loaded — id:{len(y_id)} val:{len(y_val)}\n")

    seed_results = []

    for seed in SEEDS:
        print(f"=== seed {seed} ===")
        np.random.seed(seed)

        tracemalloc.start()
        t0 = time.perf_counter()

        model = MGGP(
            inputs=u_id,
            outputs=y_id,
            nDelays=N_DELAYS,
            nTerms=N_TERMS,
            generations=GENERATIONS,
            populationSize=POP_SIZE,
            evaluationType=EVAL_TYPE,
            k=K_WINDOW,
            n_jobs=N_JOBS,
            crossoverRate=CROSSOVER,
            tournsize=TOURNSIZE,
            elitePercentage=ELITE_PCT,
            maxHeight=MAX_HEIGHT,
        )
        model.run()

        wall = time.perf_counter() - t0
        _, peak_bytes = tracemalloc.get_traced_memory()
        tracemalloc.stop()

        osa  = osa_rmse(model, y_val, u_val)
        fr   = fr_rmse(model, y_val, u_val)
        logbook = getattr(model, 'logbook', [])
        conv_g  = convergence_gen(logbook)

        throughput = (POP_SIZE * GENERATIONS) / wall if wall > 0 else float('nan')
        tpg_ms     = wall / GENERATIONS * 1000

        print(f"  wall={wall:.1f}s  t/gen={tpg_ms:.0f}ms  "
              f"throughput={throughput:.0f}eval/s  RAM={peak_bytes/1e6:.1f}MB")
        print(f"  OSA-RMSE(val)={osa:.6f}  FR-RMSE(val)={fr:.6f}  conv_gen={conv_g}")

        seed_results.append({
            'seed':            seed,
            'wall_s':          round(wall, 3),
            'tpg_ms':          round(tpg_ms, 1),
            'throughput_eps':  round(throughput, 1),
            'peak_ram_mb':     round(peak_bytes / 1e6, 1),
            'osa_rmse_val':    round(osa, 6),
            'fr_rmse_val':     round(fr, 6),
            'convergence_gen': conv_g,
        })

    print("\n=== summary ===")
    keys = ['wall_s', 'tpg_ms', 'throughput_eps', 'peak_ram_mb', 'osa_rmse_val', 'fr_rmse_val']
    means, stds = {}, {}
    for k in keys:
        vals = [r[k] for r in seed_results if not math.isnan(r[k])]
        means[k] = round(float(np.mean(vals)), 4) if vals else float('nan')
        stds[k]  = round(float(np.std(vals)),  4) if vals else float('nan')

    print(f"  wall:         {means['wall_s']:.1f} ± {stds['wall_s']:.1f} s")
    print(f"  t/gen:        {means['tpg_ms']:.0f} ± {stds['tpg_ms']:.0f} ms")
    print(f"  throughput:   {means['throughput_eps']:.0f} ± {stds['throughput_eps']:.0f} eval/s")
    print(f"  peak RAM:     {means['peak_ram_mb']:.1f} ± {stds['peak_ram_mb']:.1f} MB")
    print(f"  OSA-RMSE val: {means['osa_rmse_val']:.6f} ± {stds['osa_rmse_val']:.6f}")
    print(f"  FR-RMSE val:  {means['fr_rmse_val']:.6f} ± {stds['fr_rmse_val']:.6f}")

    output = {
        'timestamp':   datetime.now().strftime('%Y-%m-%dT%H:%M:%S'),
        'library':     'python_cpu',
        'mggp_src':    mggp_src,
        'config': {
            'popSize':    POP_SIZE,
            'nGeracoes':  GENERATIONS,
            'nDelays':    N_DELAYS,
            'nTerms':     N_TERMS,
            'maxHeight':  MAX_HEIGHT,
            'evalType':   EVAL_TYPE,
            'k':          K_WINDOW,
            'n_jobs':     N_JOBS,
            'seeds':      SEEDS,
        },
        'seeds':  seed_results,
        'mean':   means,
        'std':    stds,
    }

    ts   = datetime.now().strftime('%Y%m%d_%H%M%S')
    path = os.path.join(res_dir, f'python_bench_{ts}.json')
    with open(path, 'w') as f:
        json.dump(output, f, indent=2)
    print(f"\nResultados: {path}")


if __name__ == '__main__':
    main()
